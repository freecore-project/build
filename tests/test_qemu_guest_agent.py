class CustomizeOrderTests(unittest.TestCase):
    def test_both_image_variants_verify_before_conf_base(self):
        lists = []
        for node in ast.walk(ast.parse(CONFIG.read_text())):
            if isinstance(node, ast.Assign) and any(
                isinstance(target, ast.Name) and target.id == 'customize_tasks' for target in node.targets
            ):
                lists.append(ast.literal_eval(node.value))
        self.assertEqual(len(lists), 2)
        for tasks in lists:
            self.assertEqual(tasks.count('qemu-guest-agent'), 1)
            self.assertLess(tasks.index('qemu-guest-agent'), tasks.index('conf-base'))
            for earlier in ('remove-bits', 'remove-non-amd64'):
                if earlier in tasks:
                    self.assertLess(tasks.index(earlier), tasks.index('qemu-guest-agent'))
        self.assertTrue(CUSTOMIZER.stat().st_mode & 0o111)


class PolicyTests(unittest.TestCase):
    def parsed(self):
        parser = configparser.ConfigParser(interpolation=None)
        parser.read_string(qga.POLICY)
        return parser

    def test_policy_is_a_parseable_allow_list(self):
        parser = self.parsed()
        self.assertEqual(parser.sections(), ['general'])
        self.assertEqual(sorted(parser['general']), ['allow-rpcs', 'daemon'])
        self.assertEqual(parser['general']['daemon'], 'true')
        self.assertEqual(parser['general']['allow-rpcs'].split(','), list(qga.ALLOWED_RPCS))

    def test_allow_list_is_the_reviewed_surface(self):
        self.assertEqual(qga.ALLOWED_RPCS, (
            'guest-ping', 'guest-info', 'guest-sync', 'guest-sync-delimited',
            'guest-get-host-name', 'guest-get-osinfo', 'guest-network-get-interfaces',
            'guest-shutdown',
            'guest-fsfreeze-status', 'guest-fsfreeze-freeze', 'guest-fsfreeze-freeze-list',
            'guest-fsfreeze-thaw',
        ))
        for rpc in qga.ALLOWED_RPCS:
            self.assertRegex(rpc, r'^guest-[a-z-]+$')
            self.assertFalse(rpc.startswith(qga.FORBIDDEN_RPC_PREFIXES), rpc)
        self.assertEqual(len(set(qga.ALLOWED_RPCS)), len(qga.ALLOWED_RPCS))

    def test_freeze_family_is_allowed_whole(self):
        # A hypervisor asks for the status, freezes, then thaws: allowing only part
        # of the family would leave a backup unable to thaw what it froze.
        freeze = {rpc for rpc in qga.ALLOWED_RPCS if rpc.startswith('guest-fsfreeze-')}
        self.assertEqual(freeze, {'guest-fsfreeze-status', 'guest-fsfreeze-freeze',
                                  'guest-fsfreeze-freeze-list', 'guest-fsfreeze-thaw'})
        self.assertNotIn('guest-fsfreeze-', qga.FORBIDDEN_RPC_PREFIXES)

    def test_trim_and_everything_that_touches_guest_state_stays_excluded(self):
        for rpc in ('guest-fstrim', 'guest-exec', 'guest-exec-status', 'guest-file-open',
                    'guest-set-time', 'guest-set-user-password', 'guest-ssh-add-authorized-keys',
                    'guest-suspend-disk'):
            self.assertNotIn(rpc, qga.ALLOWED_RPCS)
            self.assertTrue(rpc.startswith(qga.FORBIDDEN_RPC_PREFIXES), rpc)

    def test_policy_comment_names_the_service_not_the_retired_enable_tunable(self):
        # the internal development record made the agent a managed service and its migration removed
        # the qemu_guest_agent_enable tunable; a new one would fight the service.
        prose = ' '.join(line.lstrip('#').strip() for line in qga.POLICY.splitlines()
                         if line.startswith('#'))
        self.assertNotIn('qemu_guest_agent_enable', prose)
        self.assertIn('QEMU Guest Agent service', prose)
        self.assertIn('qemu_guest_agent_flags', prose)

    def test_policy_leaves_transport_and_retry_at_upstream_defaults(self):
        for key in ('method', 'path', 'retry-path', 'logfile', 'fsfreeze-hook', 'block-rpcs'):
            self.assertNotIn(key, self.parsed()['general'])


class ImageGateTests(unittest.TestCase):
    AGENT_NEEDED = ('libglib-2.0.so.0', 'libgmodule-2.0.so.0', 'libthr.so.3', 'libm.so.5',
                    'libsys.so.7', 'libc.so.7')

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        for name in ('libc.so.7', 'libthr.so.3', 'libm.so.5', 'libsys.so.7'):
            self.elf(f'lib/{name}')
        self.elf('usr/local/lib/libglib-2.0.so.0.8400.4', needed=(
            'libintl.so.8', 'libpcre2-8.so.0', 'libffi.so.8', 'libiconv.so.2', 'libthr.so.3', 'libc.so.7'))
        (self.root / 'usr/local/lib/libglib-2.0.so.0').symlink_to('libglib-2.0.so.0.8400.4')
        self.elf('usr/local/lib/libgmodule-2.0.so.0', needed=('libglib-2.0.so.0', 'libc.so.7'))
        self.elf('usr/local/lib/libintl.so.8', needed=('libiconv.so.2', 'libc.so.7'))
        for name in ('libpcre2-8.so.0', 'libffi.so.8', 'libiconv.so.2'):
            self.elf(f'usr/local/lib/{name}', needed=('libc.so.7',))
        self.agent(needed=self.AGENT_NEEDED)
        self.write(qga.RC_SCRIPT, RC_SCRIPT, 0o755)
        self.write('etc/rc.conf', 'hostname="truenas"\nvmware_guest_vmblock_enable="YES"\n')
        self.write('etc/defaults/rc.conf', 'devmatch_enable="YES"\n')
        self.kernel(KERNEL_CONF)
        self.write('usr/local/share/qemu/keymaps/en-us', 'map 0x409\n')
        self.write('usr/local/share/qemu/trace-events-all', '# trace events\n')

    def write(self, relative, content, mode=0o644):
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, str):
            path.write_text(content)
        else:
            path.write_bytes(content)
        path.chmod(mode)
        return path

    def elf(self, relative, needed=(), runpath=None, strings=(), sections=None, mode=0o755):
        return self.write(relative, make_elf(needed, runpath, strings, sections), mode)

    def agent(self, needed, runpath=None, strings=None):
        if strings is None:
            strings = (*qga.ALLOWED_RPCS, *BLOCKED_SAMPLE)
        return self.elf(qga.AGENT, needed=needed, runpath=runpath, strings=strings)

    def kernel(self, conf):
        sections = {'kern_conf': conf.encode()} if conf is not None else {}
        return self.elf(qga.KERNEL, sections=sections)

    def files(self):
        return {p.relative_to(self.root) for p in self.root.rglob('*') if p.is_file() or p.is_symlink()}

    def assertRefused(self, pattern):
        with self.assertRaisesRegex(RuntimeError, pattern):
            qga.prepare_image(self.root)
        self.assertFalse((self.root / qga.POLICY_PATH).exists())

    def test_complete_fixture_installs_only_idempotent_policy(self):
        before = self.files()
        qga.prepare_image(self.root)
        qga.prepare_image(self.root)
        policy = self.root / qga.POLICY_PATH
        self.assertEqual(policy.read_text(), qga.POLICY)
        self.assertEqual(policy.stat().st_mode & 0o777, 0o644)
        self.assertEqual(policy.parent.stat().st_mode & 0o777, 0o755)
        self.assertEqual(self.files() - before, {Path(qga.POLICY_PATH)})

    def test_elf_reader_matches_the_dynamic_section(self):
        needed, runpath = qga.ElfFile(self.root / qga.AGENT).dynamic()
        self.assertEqual(needed, list(self.AGENT_NEEDED))
        self.assertEqual(runpath, [])
        self.agent(needed=('libc.so.7',), runpath='/usr/local/lib:/usr/local/lib/qemu')
        self.assertEqual(qga.ElfFile(self.root / qga.AGENT).dynamic(),
                         (['libc.so.7'], ['/usr/local/lib', '/usr/local/lib/qemu']))
        self.assertIsNone(qga.ElfFile(self.root / qga.AGENT).section('kern_conf'))
        self.write('usr/local/bin/not-elf', 'text')
        with self.assertRaisesRegex(RuntimeError, 'Not an ELF object'):
            qga.ElfFile(self.root / 'usr/local/bin/not-elf')

    def test_missing_agent_binary_fails_closed(self):
        (self.root / qga.AGENT).unlink()
        self.assertRefused('binary is missing')

    def test_missing_shared_library_fails_closed(self):
        (self.root / 'usr/local/lib/libpcre2-8.so.0').unlink()
        self.assertRefused('shared libraries are missing.*libpcre2-8.so.0')

    def test_dangling_library_symlink_fails_closed(self):
        (self.root / 'usr/local/lib/libglib-2.0.so.0.8400.4').unlink()
        self.assertRefused('shared libraries are missing.*libglib-2.0.so.0')

    def test_library_symlink_escaping_the_image_is_not_followed(self):
        real = self.root / 'usr/local/lib/libffi.so.8'
        real.unlink()
        real.symlink_to('../../../../../../../lib/libc.so.7')
        self.assertRefused('shared libraries are missing.*libffi.so.8')

    def test_emulator_library_closure_is_rejected(self):
        self.elf('usr/local/lib/libpixman-1.so.0', needed=('libc.so.7',))
        self.agent(needed=(*self.AGENT_NEEDED, 'libpixman-1.so.0'))
        self.assertRefused('outside the agent-only closure.*libpixman-1.so.0')

    def test_runpath_libraries_resolve_inside_the_image_only(self):
        (self.root / 'usr/local/lib/libintl.so.8').rename(self.root / 'usr/local/lib/libintl.so.8.moved')
        self.elf('usr/local/lib/gettext/libintl.so.8', needed=('libiconv.so.2', 'libc.so.7'))
        self.agent(needed=(*self.AGENT_NEEDED, 'libintl.so.8'), runpath='/usr/local/lib/gettext')
        qga.prepare_image(self.root)
        (self.root / qga.POLICY_PATH).unlink()
        self.agent(needed=(*self.AGENT_NEEDED, 'libintl.so.8'), runpath='$ORIGIN/../lib/gettext')
        self.assertRefused('shared libraries are missing.*libintl.so.8')

    def test_rpc_missing_from_the_built_agent_fails_closed(self):
        strings = [rpc for rpc in qga.ALLOWED_RPCS if rpc != 'guest-network-get-interfaces']
        self.agent(needed=self.AGENT_NEEDED, strings=strings)
        self.assertRefused('not implemented by the built agent.*guest-network-get-interfaces')

    def test_rc_script_must_exist_and_default_to_disabled(self):
        script = self.root / qga.RC_SCRIPT
        script.chmod(0o644)
        self.assertRefused('rc script is not executable')
        self.write(qga.RC_SCRIPT, RC_SCRIPT.replace(':-"NO"', ':-"YES"'), 0o755)
        self.assertRefused('default-disabled service')
        self.write(qga.RC_SCRIPT, RC_SCRIPT.replace('rcvar=qemu_guest_agent_enable', 'rcvar=other'), 0o755)
        self.assertRefused('expected rcvar')
        script.unlink()
        self.assertRefused('rc script is missing')

    def test_image_configuration_must_not_enable_the_agent(self):
        self.write('etc/rc.conf.d/qemu_guest_agent', 'qemu_guest_agent_enable="NO"\n')
        qga.prepare_image(self.root)
        (self.root / qga.POLICY_PATH).unlink()
        self.write('etc/rc.conf.d/qemu_guest_agent', 'qemu_guest_agent_enable="YES"\n')
        self.assertRefused('enables the QEMU Guest Agent.*etc/rc.conf.d/qemu_guest_agent')
        (self.root / 'etc/rc.conf.d/qemu_guest_agent').unlink()
        with (self.root / 'etc/rc.conf').open('a') as handle:
            handle.write('qemu_guest_agent_enable=YES\n')
        self.assertRefused('enables the QEMU Guest Agent.*etc/rc.conf')

    def test_emulator_tools_or_firmware_payload_is_rejected_on_an_agent_only_image(self):
        # without a system emulator the image is agent-only: any other qemu
        # tool or firmware is a leak
        for stray in ('usr/local/bin/qemu-img', 'usr/local/libexec/qemu-bridge-helper',
                      'usr/local/share/qemu/bios-256k.bin',
                      'usr/local/share/qemu/firmware/50-edk2-x86_64.json'):
            with self.subTest(stray=stray):
                path = self.write(stray, b'\x7fELF stray payload', 0o755)
                try:
                    self.assertRefused('beyond the guest agent.*' + stray)
                finally:
                    path.unlink()
        qga.prepare_image(self.root)

    def test_the_emulated_guest_lane_payload_is_expected_beside_a_system_emulator(self):
        # the internal development record: a qemu-system-* emulator means the image ships the
        # emulated-guest lane, whose tools and firmware are its payload; the
        # agent's own checks (disabled by default, closure, policy) still run
        for name in ('usr/local/bin/qemu-system-aarch64', 'usr/local/bin/qemu-img',
                     'usr/local/libexec/qemu-bridge-helper', 'usr/local/share/qemu/bios-256k.bin'):
            self.write(name, b'\x7fELF lane payload', 0o755)
        self.write('etc/rc.conf.d/qemu_guest_agent', 'qemu_guest_agent_enable="YES"\n')
        self.assertRefused('enables the QEMU Guest Agent.*etc/rc.conf.d/qemu_guest_agent')
        (self.root / 'etc/rc.conf.d/qemu_guest_agent').unlink()
        qga.prepare_image(self.root)
        self.assertTrue((self.root / qga.POLICY_PATH).exists())

    def test_kernel_without_the_console_driver_fails_closed(self):
        self.kernel(KERNEL_CONF.replace('device\tvirtio_console\n', ''))
        self.assertRefused('without device virtio_console')
        self.kernel(None)
        self.assertRefused('no embedded configuration')
        (self.root / qga.KERNEL).unlink()
        self.assertRefused('Kernel is missing')

    def test_unexpected_policy_is_not_overwritten(self):
        self.write(qga.POLICY_PATH, 'operator-owned contents')
        with self.assertRaisesRegex(RuntimeError, 'unexpected QEMU Guest Agent policy'):
            qga.prepare_image(self.root)
        self.assertEqual((self.root / qga.POLICY_PATH).read_text(), 'operator-owned contents')

    def test_policy_symlink_is_not_followed(self):
        target = self.root / 'untouched'
        target.write_text('operator-owned')
        policy = self.root / qga.POLICY_PATH
        policy.parent.mkdir(parents=True)
        policy.symlink_to(target)
        with self.assertRaisesRegex(RuntimeError, 'symlinked QEMU Guest Agent policy'):
            qga.prepare_image(self.root)
        self.assertEqual(target.read_text(), 'operator-owned')

    def test_running_after_conf_base_is_refused(self):
        local_etc = self.root / 'usr/local/etc'
        (self.root / 'etc/local').mkdir()
        for path in sorted(local_etc.rglob('*'), reverse=True):
            path.rmdir() if path.is_dir() else path.unlink()
        local_etc.rmdir()
        local_etc.symlink_to('/etc/local')
        with self.assertRaisesRegex(RuntimeError, 'must run before conf-base'):
            qga.prepare_image(self.root)
        self.assertEqual(list((self.root / 'etc/local').iterdir()), [])


