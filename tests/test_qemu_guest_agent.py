def make_elf(needed=(), runpath=None, strings=(), sections=None):
    """Build a minimal little-endian ELF64 object with a dynamic section."""
    dynstr, offsets = bytearray(b'\0'), {}
    for text in [*needed, *([runpath] if runpath is not None else [])]:
        offsets[text] = len(dynstr)
        dynstr.extend(text.encode() + b'\0')
    dynamic = bytearray()
    for name in needed:
        dynamic += struct.pack('<qQ', qga.ElfFile.DT_NEEDED, offsets[name])
    if runpath is not None:
        dynamic += struct.pack('<qQ', qga.ElfFile.DT_RUNPATH, offsets[runpath])
    dynamic += struct.pack('<qQ', qga.ElfFile.DT_NULL, 0)
    rodata = b''.join(text.encode() + b'\0' for text in strings)

    entries = [('.dynstr', 3, bytes(dynstr), 0, 0), ('.dynamic', 6, bytes(dynamic), 1, 16),
               ('.rodata', 1, rodata, 0, 0)]
    entries += [(name, 1, data, 0, 0) for name, data in (sections or {}).items()]
    shstrtab, name_offsets = bytearray(b'\0'), []
    for name in [entry[0] for entry in entries] + ['.shstrtab']:
        name_offsets.append(len(shstrtab))
        shstrtab.extend(name.encode() + b'\0')
    entries.append(('.shstrtab', 3, bytes(shstrtab), 0, 0))

    body, headers = bytearray(), [b'\0' * 64]
    for (name, kind, data, link, entsize), name_offset in zip(entries, name_offsets):
        offset = 64 + len(body)
        body.extend(data)
        body.extend(b'\0' * (-len(body) % 8))
        headers.append(struct.pack('<IIQQQQIIQQ', name_offset, kind, 0, 0, offset, len(data),
                                   link, 0, 8, entsize))
    header = b'\x7fELF' + bytes([2, 1, 1, 9]) + b'\0' * 8
    header += struct.pack('<HHIQQQIHHHHHH', 3, 0x3e, 1, 0, 0, 64 + len(body), 0, 64, 56, 0, 64,
                          len(headers), len(headers) - 1)
    return header + bytes(body) + b''.join(headers)


def port_additions():
    """Every `ports +=` addition in the profile as (origin, package or None)."""
    additions = []
    for node in ast.walk(ast.parse(PORTS_SYSTEM.read_text())):
        if not isinstance(node, ast.AugAssign) or not isinstance(node.target, ast.Name):
            continue
        if node.target.id != 'ports':
            continue
        if isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            additions.append((node.value.value, None))
        elif isinstance(node.value, ast.Dict):
            fields = {key.value: value for key, value in zip(node.value.keys, node.value.values)
                      if isinstance(key, ast.Constant)}
            package = fields['package'].value if 'package' in fields else None
            additions.append((fields['name'].value, package))
    return additions


def kernel_config_lines(keyword):
    names = []
    for line in KERNEL_CONFIG.read_text().splitlines():
        fields = line.partition('#')[0].split()
        if len(fields) >= 2 and fields[0] == keyword:
            names.append(fields[1])
    return names


class SelectionTests(unittest.TestCase):
    def test_guest_agent_flavor_is_selected_once_by_package_name(self):
        additions = port_additions()
        self.assertEqual([a for a in additions if a[0] == GUEST_AGENT[0]], [GUEST_AGENT])

    def test_only_the_agent_and_the_emulated_guest_lane_are_selected(self):
        # the internal development record/#133: the emulated-guest lane ships the user-mode emulators
        # and one system-emulator flavour beside the agent; nothing else from
        # the qemu family (no default/x11 flavour, no second origin)
        qemu = sorted(a for a in port_additions() if 'qemu' in a[0].lower())
        self.assertEqual(qemu, sorted([
            GUEST_AGENT,
            ('emulators/qemu-user-static', None),
            ('emulators/qemu@nox11', 'qemu-nox11'),
        ]))

    def test_existing_vmware_and_xen_guest_tools_are_retained(self):
        additions = port_additions()
        self.assertIn(('emulators/open-vm-tools@nox11', 'open-vm-tools-nox11'), additions)
        self.assertIn(('sysutils/xe-guest-utilities', None), additions)

    def test_profile_never_enables_the_agent(self):
        for path in sorted(PROFILE.rglob('*')):
            if path.is_file():
                self.assertNotRegex(path.read_text(errors='ignore'),
                                    r'^\s*qemu_guest_agent_enable\s*=', msg=path.as_posix())


